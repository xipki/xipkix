  @Test
  public void testCmpMessages() throws Exception {
    String[] files = {"cmp-ir.der", "cmp-ip-capubs.der", "cmp-cr-keyenc.der",
        "cmp-cp-keyenc.der", "cmp-p10cr.der", "cmp-cp.der", "cmp-kur.der", "cmp-kup.der",
        "cmp-certconf.der", "cmp-certconf-2.der", "cmp-certconf-3.der",
        "cmp-pkiconf.der", "cmp-pkiconf-2.der", "cmp-pkiconf-3.der",
        "cmp-rr.der", "cmp-rp.der", "cmp-error.der",
        "cmp-ip-waiting.der", "cmp-pollreq.der", "cmp-pollrep.der",
        "cmp-genm.der", "cmp-genp.der", "cmp-genm-cacerts.der", "cmp-genp-cacerts.der",
        "cmp-genm-crls.der", "cmp-genp-crls.der", "cmp-genm-rootca.der", "cmp-genp-rootca.der"};
    for (String file : files) {
      assertRoundTrip(file, PKIMessage::fromEncoded);
    }

    // CertRepMessage with caPubs
    PKIMessage ip = PKIMessage.fromEncoded(read("cmp-ip-capubs.der"));
    Assert.assertEquals(PKIBody.tag_ip, ip.getBody().getTagNo());
    Assert.assertNotNull("caPubs", ip.getBody().getIp().getCaPubs());
    Assert.assertEquals("number of caPubs", 1, ip.getBody().getIp().getCaPubs().size());

    // ErrorMsgContent
    PKIMessage error = PKIMessage.fromEncoded(read("cmp-error.der"));
    Assert.assertEquals(PKIBody.tag_error, error.getBody().getTagNo());
  }

  // ---------------- helpers ----------------

  /**
   * Parses the content of the given file, and checks that the re-encoded object equals the
   * file content.
   */
  static Asn1Encodable assertRoundTrip(String file, Parser parser) throws Exception {
    return assertRoundTrip(file, read(file), parser);
  }

  static Asn1Encodable assertRoundTrip(String name, byte[] encoded, Parser parser)
      throws Exception {
    Asn1Encodable obj;
    try {
      obj = parser.parse(encoded);
    } catch (Exception e) {
      throw new AssertionError(name + ": could not parse: " + e.getMessage(), e);
    }

    Assert.assertArrayEquals(name + ": re-encoded", encoded, obj.getEncoded());

    // parse the re-encoded object again: must be equal to the first one.
    Asn1Encodable obj2 = parser.parse(obj.getEncoded());
    Assert.assertEquals(name + ": re-parsed", obj.toAsn1Primitive(), obj2.toAsn1Primitive());
    ToStringAssert.assertPrintable(name, obj);
    return obj;
  }

  private static SignedData signedData(String file) throws Exception {
    ContentInfo ci = ContentInfo.fromEncoded(read(file));
    return SignedData.fromAsn1(ci.getContent().asSequence());
  }

  private static byte[] tbsOf(byte[] cert) throws CodecException {
    return Asn1Sequence.fromEncoded(cert).getSequenceAt(0).getEncoded();
  }

  static byte[] read(String file) throws IOException {
    try (InputStream is = Asn1VectorsTest.class.getResourceAsStream("/asn1-vectors/" + file)) {
      if (is == null) {
        throw new IOException("resource not found: " + file);
      }
      return is.readAllBytes();
    }
  }

  /**
   * Maps the CMS content types to the parsers.
   */
  private static class CmsTypes {

    static Parser parser(Asn1Oid contentType) {
      if (CmsOIDs.signedData.equals(contentType)) {
        return e -> SignedData.fromAsn1(Asn1Sequence.fromEncoded(e));
      } else if (CmsOIDs.envelopedData.equals(contentType)) {
        return e -> org.xipki.pkix.asn1.cms.EnvelopedData.fromAsn1(Asn1Sequence.fromEncoded(e));
      } else if (CmsOIDs.encryptedData.equals(contentType)) {
        return e -> org.xipki.pkix.asn1.cms.EncryptedData.fromAsn1(Asn1Sequence.fromEncoded(e));
      } else if (CmsOIDs.authEnvelopedData.equals(contentType)
          || CmsOIDs.digestedData.equals(contentType)) {
        // AuthEnvelopedData and DigestedData are not implemented
        return null;
      } else {
        throw new IllegalArgumentException("unsupported content type " + contentType.getId());
      }
    }
  }

